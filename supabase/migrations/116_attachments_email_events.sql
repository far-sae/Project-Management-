-- 116_attachments_email_events.sql
--
-- Adds the two related-list features the user explicitly asked to wire
-- on the Lead and Contact drawers:
--
--   1. attachments      — files uploaded against a polymorphic CRM
--                         entity (lead / contact / client / deal /
--                         task / meeting / call). Bytes live in the
--                         'attachments' Supabase Storage bucket; this
--                         table tracks the metadata + a stable path so
--                         the UI can list / download / delete.
--
--   2. email_events     — per-entity timeline of emails sent to or
--                         from a CRM record. Populated by the
--                         notify-send-gmail (outbound) and
--                         gmail-inbound (inbound) edge functions.
--
-- Both tables share the same polymorphic relationship shape and the
-- same org-member RLS so they can be exposed identically in the
-- drawers.

set search_path = public;

-- ---------------------------------------------------------------------------
-- attachments
-- ---------------------------------------------------------------------------
create table if not exists public.attachments (
  attachment_id     uuid primary key default gen_random_uuid(),
  organization_id   uuid not null,

  -- Polymorphic anchor — exactly one logical parent at a time. We
  -- don't add per-type FKs because the entity row may be deleted
  -- independently and we don't want orphaned-cascade surprises;
  -- background cleanup (or list-time filtering) handles dangling rows.
  entity_type       text not null,    -- 'lead' | 'contact' | 'client' | 'deal' | 'task' | 'meeting' | 'call'
  entity_id         uuid not null,

  file_name         text not null,
  mime_type         text,
  size_bytes        bigint not null default 0,

  -- Path inside the 'attachments' Storage bucket. Convention:
  --   <organization_id>/<entity_type>/<entity_id>/<attachment_id>-<file_name>
  -- This keeps every org's blobs in their own folder which makes
  -- audit + cleanup trivial.
  storage_path      text not null,

  uploaded_by       uuid,
  uploaded_by_name  text,

  created_at        timestamptz not null default now(),

  check (entity_type in ('lead','contact','client','deal','task','meeting','call'))
);

create index if not exists idx_attachments_entity
  on public.attachments (entity_type, entity_id, created_at desc);
create index if not exists idx_attachments_org
  on public.attachments (organization_id, created_at desc);

alter table public.attachments enable row level security;

grant select on table public.attachments to anon;
grant select, insert, delete on table public.attachments to authenticated;

drop policy if exists "anon_no_attachments"           on public.attachments;
drop policy if exists "members_view_attachments"      on public.attachments;
drop policy if exists "members_create_attachments"    on public.attachments;
drop policy if exists "uploader_or_admin_delete"      on public.attachments;

create policy "anon_no_attachments"
  on public.attachments for select to anon using (false);

create policy "members_view_attachments"
  on public.attachments for select to authenticated
  using (public.is_org_member(organization_id));

create policy "members_create_attachments"
  on public.attachments for insert to authenticated
  with check (
    public.is_org_member(organization_id)
    and (uploaded_by is null or uploaded_by = auth.uid())
  );

create policy "uploader_or_admin_delete"
  on public.attachments for delete to authenticated
  using (
    uploaded_by = auth.uid()
    or public.is_org_admin_or_owner(organization_id)
  );


-- ---------------------------------------------------------------------------
-- attachments Storage bucket
--
-- Created via storage.buckets so it's reproducible across environments.
-- We keep it private (public = false) so reads go through signed URLs
-- generated by the service layer. Bucket-level RLS uses the same
-- pattern as the table — only org members can read/write blobs whose
-- path prefix matches their org_id.
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
  values ('attachments', 'attachments', false)
  on conflict (id) do nothing;

-- Storage RLS — path convention is <org_id>/<entity_type>/<entity_id>/<file>.
-- We extract the org_id from the first path segment and check membership.
do $$
begin
  if exists (select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname='attachments_member_read') then
    drop policy "attachments_member_read" on storage.objects;
  end if;
  if exists (select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname='attachments_member_write') then
    drop policy "attachments_member_write" on storage.objects;
  end if;
  if exists (select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname='attachments_member_delete') then
    drop policy "attachments_member_delete" on storage.objects;
  end if;
end $$;

create policy "attachments_member_read"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'attachments'
    and public.is_org_member((string_to_array(name, '/'))[1]::uuid)
  );

create policy "attachments_member_write"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'attachments'
    and public.is_org_member((string_to_array(name, '/'))[1]::uuid)
  );

create policy "attachments_member_delete"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'attachments'
    and public.is_org_member((string_to_array(name, '/'))[1]::uuid)
  );


-- ---------------------------------------------------------------------------
-- email_events
--
-- One row per Gmail send/receive against a CRM entity. The unique
-- (organization_id, message_id) guard prevents duplicate logging when
-- the inbound webhook retries.
-- ---------------------------------------------------------------------------
create table if not exists public.email_events (
  event_id          uuid primary key default gen_random_uuid(),
  organization_id   uuid not null,

  entity_type       text,         -- 'lead' | 'contact' | 'client' | 'deal' | null
  entity_id         uuid,

  direction         text not null,         -- 'outbound' | 'inbound'
  status            text not null default 'sent',  -- sent | delivered | failed | received

  subject           text,
  snippet           text,                  -- first 200 chars of body for preview
  from_email        text,
  to_emails         text[] not null default '{}'::text[],
  cc_emails         text[] not null default '{}'::text[],

  message_id        text,                  -- Gmail Message-Id header (for dedup)
  thread_id         text,                  -- Gmail threadId (for grouping)
  gmail_id          text,                  -- Gmail API resource id

  sender_user_id    uuid,                  -- which org user pressed send (outbound)
  sender_name       text,

  -- Free-form metadata so the worker can stash error reasons,
  -- attachment counts, labels, etc. without schema churn.
  metadata          jsonb not null default '{}'::jsonb,

  occurred_at       timestamptz not null default now(),
  created_at        timestamptz not null default now(),

  check (direction in ('outbound','inbound')),
  check (status in ('sent','delivered','failed','received')),
  check (entity_type is null or entity_type in ('lead','contact','client','deal'))
);

create unique index if not exists uniq_email_events_org_message
  on public.email_events (organization_id, message_id)
  where message_id is not null;
create index if not exists idx_email_events_entity
  on public.email_events (entity_type, entity_id, occurred_at desc);
create index if not exists idx_email_events_org
  on public.email_events (organization_id, occurred_at desc);

alter table public.email_events enable row level security;

grant select on table public.email_events to anon;
grant select, insert on table public.email_events to authenticated;

drop policy if exists "anon_no_email_events"        on public.email_events;
drop policy if exists "members_view_email_events"   on public.email_events;
drop policy if exists "members_log_email_events"    on public.email_events;

create policy "anon_no_email_events"
  on public.email_events for select to anon using (false);

create policy "members_view_email_events"
  on public.email_events for select to authenticated
  using (public.is_org_member(organization_id));

-- Inserts happen from edge functions with service-role keys, but we
-- also allow members to log a manual entry (e.g. "I emailed them from
-- my personal account, log it for the timeline"). Restricting to
-- members keeps the channel clean.
create policy "members_log_email_events"
  on public.email_events for insert to authenticated
  with check (
    public.is_org_member(organization_id)
    and (sender_user_id is null or sender_user_id = auth.uid())
  );
